const emptySnapshot = (): BuildSnapshot => ({ money: 0, maxPower: 0, powerUsed: 0, installed: [], mods: [], modCount: 0 });

export function snapshotBuild(run: RunView): BuildSnapshot {
  const mods = Object.entries(run.mods).map(([target, items]) => {
    const byName: Record<string, number> = {};
    for (const m of items) byName[m.note ?? '?'] = (byName[m.note ?? '?'] ?? 0) + 1;
    return { target, copies: items.length, byName, items: structuredClone(items) };
  });
  return {
    money: run.money,
    maxPower: run.maxPower,
    powerUsed: run.powerUsed,
    installed: run.installed.map(i => ({
      id: i.id, uid: i.uid, offerKey: i.offerKey, name: i.name, mount: i.mountId, mounts: i.mounts, power: i.power ?? i.def.powerCost, type: i.def.type,
      parts: i.parts?.map(p => p.id), via: i.via, paid: i.paid,
    })),
    mods,
    modCount: mods.reduce((n, m) => n + m.copies, 0),
    dormant: run.dormantKeys?.() ?? [],
  };
}

type OfferLike = {
  kind: 'machine' | 'modifier'; key: string; name: string; desc: string; price: number; power?: number; pieces?: number;
  target?: { key: string; label: string }; scope?: string; origin?: string; weight?: number; synergies?: string[];
};
export function summarizeOffer(o: OfferLike, check?: (o: OfferLike) => { ok: boolean }): OfferSummary {
  const s: OfferSummary = { kind: o.kind, key: o.key, name: o.name, desc: o.desc, price: o.price };
  if (o.kind === 'machine') {
    s.power = o.power;
    if (o.pieces) s.pieces = o.pieces;
    if (check) s.feasibility = check(o).ok ? 'now' : 'after-selling';
  }
  if (o.target) {
    s.target = o.target.key;
    s.targetLabel = o.target.label;
  }
  if (o.scope) s.scope = o.scope;
  if (o.origin) s.origin = o.origin;
  if (o.weight !== undefined) s.weight = o.weight;
  if (o.synergies?.length) s.synergies = o.synergies;
  return s;
}

const RAMP_PART = /-(cp|gate)$/;

export class RunRecorder {
  rec: RunRecord | null = null;
  private store: Store | null;
  private now: () => number;
  private build: BuildInfo;
  private pitch: PitchRecord | null = null;
  private swingOpen = false;
  /** Ball id → points on its current ride (for best-ride stats). */
  private rides = new Map<number, number>();
  private seq = 0;
  private frames: number[] = [];

  constructor(opts: { store?: Store | null; build: BuildInfo; now?: () => number }) {
    this.store = opts.store ?? null;
    this.build = opts.build;
    this.now = opts.now ?? (() => Date.now());
  }

  get challenge(): ChallengeRecord | null {
    const c = this.rec?.challenges[this.rec.challenges.length - 1];
    return c && c.outcome === 'open' ? c : null;
  }

  // ───────── run lifecycle ─────────

  /**
   * Begin a new run. If storage holds an unfinished run (reload/closed tab), it is first archived as
   * `interrupted` so its finished history stays downloadable. A finished previous run is kept as "last".
   */
  startRun(meta: { route: string; theme: string; runSeed?: number }) {
    this.recover();
    const t = this.now();
    this.rec = {
      schema: SCHEMA,
      runId: makeRunId(t),
      build: this.build,
      route: meta.route,
      theme: meta.theme,
      runSeed: meta.runSeed,
      startedAt: t,
      outcome: 'in-progress',
      activeMs: 0,
      challenges: [],
      ledger: [],
      ledgerDropped: 0,
      highlights: [],
      money: { earned: 0, spent: 0, rerollSpend: 0, purchases: 0, rerolls: 0 },
      notes: [],
    };
    this.pitch = null;
    this.seq = 0;
    this.frames = [];
    this.rides.clear();
    this.save();
    return this.rec;
  }

  /** Move an unfinished stored run to "last" as interrupted (honest partial data). Returns it if any. */
  recover(): RunRecord | null {
    const raw = this.safeGet(STORE_KEYS.current);
    if (!raw) return null;
    let r: RunRecord;
    try {
      r = JSON.parse(raw);
    } catch {
      this.safeRemove(STORE_KEYS.current);
      return null;
    }
    if (!SCHEMAS_READABLE.includes(r.schema)) return null;
    if (this.rec && r.runId === this.rec.runId) return null;
    // A run with no played pitch carries no data (e.g. reload on the first READY screen): drop it so it
    // can never push a real run out of the archive.
    const empty = r.challenges.every(c => c.pitches.length === 0);
    if (r.outcome === 'in-progress' && !empty) {
      r.outcome = 'interrupted';
      r.endedAt = r.savedAt ?? r.startedAt;
      for (const c of r.challenges) {
        if (c.outcome !== 'open') continue;
        c.outcome = 'interrupted';
        c.endedAt = r.endedAt;
        for (const p of c.pitches) if (p.outcome === 'open') p.outcome = 'interrupted';
      }
      r.notes.push('Run was interrupted (page reload, closed tab or navigation). Data after the last save point is not available; an unfinished pitch is marked interrupted, never completed.');
      this.archive(r);
    }
    this.safeRemove(STORE_KEYS.current);
    return r;
  }

  /** Archived runs (terminal or interrupted), most recent first, at most LIMITS.archivedRuns. */
  archivedRuns(): RunRecord[] {
    const raw = this.safeGet(STORE_KEYS.archive);
    if (!raw) return [];
    try {
      const list = JSON.parse(raw);
      return Array.isArray(list) ? list.filter(r => SCHEMAS_READABLE.includes(r?.schema)) : [];
    } catch {
      return [];
    }
  }

  /** The most recent archived run, for download after a restart or reload. */
  lastRun(): RunRecord | null {
    return this.archivedRuns()[0] ?? null;
  }

  private archive(r: RunRecord) {
    const list = [r, ...this.archivedRuns().filter(x => x.runId !== r.runId)].slice(0, LIMITS.archivedRuns);
    // On a full quota keep fewer older runs rather than losing the newest one.
    for (let n = list.length; n >= 1; n--) if (this.safeSet(STORE_KEYS.archive, JSON.stringify(list.slice(0, n)), n > 1)) return true;
    return false;
  }

  /** Terminal: failed or completed. The record is archived as "last" so it survives a restart. */
  endRun(outcome: 'failed' | 'completed') {
    const r = this.rec;
    if (!r || r.outcome !== 'in-progress') return r;
    r.outcome = outcome;
    r.endedAt = this.now();
    this.closeFrames();
    this.log('runEnd', { outcome });
    this.save();
    this.archive(r);
    this.safeRemove(STORE_KEYS.current);
    return r;
  }

  // ───────── challenge lifecycle ─────────

  startChallenge(run: RunView, maxStrikes: number) {
    const r = this.rec;
    if (!r) return;
    if (this.challenge) return; // already open (duplicate call)
    if (r.challenges.some(c => c.n === run.challenge)) return; // never record a challenge twice
    const t = this.now();
    r.challenges.push({
      n: run.challenge,
      inning: Math.ceil(run.challenge / 3),
      target: run.target,
      outcome: 'open',
      score: 0,
      startedAt: t,
      activeMs: 0,
      strikesUsed: 0,
      maxStrikes,
      pitches: [],
      startBuild: snapshotBuild(run),
      multPeak: 10,
      multEnd: 10,
      sources: {},
      mechanisms: {},
      ramps: {},
      multGains: {},
      scoops: { catches: 0, ejects: 0 },
      deckRally: { starts: 0, returned: 0, drained: 0, removed: 0, rallyHits: 0, rallyGain: 0, hrCompletion: 0, hrCompletions: 0, deckAwarded: 0, deckHits: 0 },
      multiballs: { activations: 0, ballsLaunched: 0 },
      attributed: 0,
      unattributed: 0,
      bestEvents: [],
    });
    this.pitch = null;
    this.rides.clear();
    this.log('challengeStart', { target: run.target, money: run.money, power: `${run.powerUsed}/${run.maxPower}` });
    this.save();
  }

  /**
   * Finalize the open challenge exactly once (clear or 3rd strike). Call BEFORE Run.clear() so the
   * end snapshot is the pre-reward machine that actually played it.
   */
  endChallenge(run: RunView, sim: SimView, outcome: 'cleared' | 'failed') {
    const c = this.challenge;
    if (!c) return null;
    if (this.pitch) this.closePitch(sim, outcome === 'cleared' ? 'clear' : 'drain');
    c.outcome = outcome;
    c.endedAt = this.now();
    c.score = sim.rules.score;
    c.strikesUsed = sim.rules.strikes;
    c.maxStrikes = sim.rules.maxStrikes;
    c.multEnd = sim.rules.multTenths;
    c.endBuild = snapshotBuild(run);
    c.unattributed = c.score - c.attributed;
    this.log('challengeEnd', { outcome, score: c.score, target: c.target, strikesUsed: c.strikesUsed });
    this.save();
    return c;
  }

  // ───────── between challenges (build/economy ledger) ─────────

  /** After Run.clear(): reward money, inning Power grant, and the free draft offers. */
  afterClear(run: RunView & { draft: Parameters<typeof summarizeOffer>[0][] }, earned: number) {
    const r = this.rec;
    if (!r) return;
    const c = r.challenges.find(c => c.n === run.challenge);
    if (c && c.outcome === 'cleared' && c.reward === undefined) {
      c.reward = earned;
      r.money.earned += earned;
      this.log('clearReward', { earned, money: run.money });
      if (run.powerGrant) this.log('powerGrant', { ...run.powerGrant });
      // V2: structural section unlock (free; physically present from the next challenge's board on)
      const sg = (run as any).sectionGrant as { id: string; name: string } | null | undefined;
      if (sg) this.log('sectionUnlock', { ...sg });
      this.log('draftOffers', { offers: run.draft.map(o => summarizeOffer(o, (run as any).check?.bind(run))) });
      this.save();
    }
  }

  draftTaken(run: RunView, offer: Parameters<typeof summarizeOffer>[0], declined: Parameters<typeof summarizeOffer>[0][], mount?: string) {
    this.log('draftTaken', { offer: summarizeOffer(offer), declined: declined.map(o => summarizeOffer(o)), mount });
    this.logAcquire(run, offer, 'draft', mount);
    this.save();
  }

  shopOffers(run: RunView & { shop: Parameters<typeof summarizeOffer>[0][] }, reason: 'open' | 'reroll') {
    this.log('shopOffers', { reason, offers: run.shop.map(o => summarizeOffer(o)), money: run.money });
  }

  purchase(run: RunView, offer: Parameters<typeof summarizeOffer>[0], moneyBefore: number, mount?: string) {
    const r = this.rec;
    if (!r) return;
    r.money.spent += offer.price;
    r.money.purchases++;
    this.log('purchase', { offer: summarizeOffer(offer), price: offer.price, moneyBefore, moneyAfter: run.money, mount, power: `${run.powerUsed}/${run.maxPower}` });
    this.logAcquire(run, offer, 'shop', mount);
    this.save();
  }

  reroll(run: RunView, price: number, moneyBefore: number) {
    const r = this.rec;
    if (!r) return;
    r.money.spent += price;
    r.money.rerollSpend += price;
    r.money.rerolls++;
    this.log('reroll', { price, moneyBefore, moneyAfter: run.money });
  }

  /** A sale between challenges: refund, Power reclaimed, modifiers going dormant / waking. */
  sale(run: RunView, info: { uid: string; name: string; refund: number; powerFreed: number; powerBefore: string; powerAfter: string; dormant: { key: string; names: string[] }[]; waking: { key: string; names: string[] }[] }, dormantBefore: string[]) {
    const r = this.rec;
    if (!r) return;
    r.money.earned += info.refund;
    (r.money as any).refunds = ((r.money as any).refunds ?? 0) + info.refund;
    (r.money as any).sales = ((r.money as any).sales ?? 0) + 1;
    this.log('sale', { item: info.uid, name: info.name, refund: info.refund, powerFreed: info.powerFreed, power: `${info.powerBefore} → ${info.powerAfter}`, money: run.money, dormant: info.dormant, waking: info.waking });
    this.boardDiff(run, dormantBefore);
    this.save();
  }

  /** Log modifiers that became dormant or reactivated since `dormantBefore` (install / sale). */
  boardDiff(run: RunView, dormantBefore: string[]) {
    const now = run.dormantKeys?.() ?? [];
    const woke = dormantBefore.filter(k => !now.includes(k));
    const slept = now.filter(k => !dormantBefore.includes(k));
    const names = (k: string) => (run.mods[k] ?? []).map(m => m.note ?? '?');
    if (woke.length) this.log('modsReactivated', { keys: woke.map(k => ({ key: k, names: names(k) })) });
    if (slept.length) this.log('modsDormant', { keys: slept.map(k => ({ key: k, names: names(k) })) });
  }

  nextChallenge(run: RunView) {
    this.log('next', { toChallenge: run.challenge, money: run.money, power: `${run.powerUsed}/${run.maxPower}` });
  }

  private logAcquire(run: RunView, offer: Parameters<typeof summarizeOffer>[0], via: 'draft' | 'shop', mount?: string) {
    if (offer.kind === 'machine') {
      const inst = [...run.installed].reverse().find(i => i.offerKey === offer.key && (!mount || i.mountId === mount || (i as any).placement === mount));
      if (inst)
        this.log('install', {
          via, item: inst.uid, id: inst.id, offerKey: inst.offerKey, name: inst.name, mount: inst.mountId, mounts: inst.mounts,
          parts: inst.parts?.map(p => p.id), power: inst.power ?? inst.def.powerCost, paid: inst.paid ?? 0, powerAfter: `${run.powerUsed}/${run.maxPower}`,
        });
    } else if (offer.target) {
      const stack = run.mods[offer.target.key] ?? [];
      const copy = stack.filter(m => m.note === offer.name).length;
      this.log('modifier', { via, key: offer.key, name: offer.name, effect: offer.desc, target: offer.target.key, targetLabel: offer.target.label, copy, stackOnTarget: stack.length });
    }
  }

  // ───────── live play ─────────

  /** Active play time (live ball, not paused). Called from the frame loop with real milliseconds. */
  tick(ms: number, live: boolean) {
    if (!live || !this.rec || this.rec.outcome !== 'in-progress') return;
    this.rec.activeMs += ms;
    const c = this.challenge;
    if (c) c.activeMs += ms;
  }

  /** Frame-time sample (bounded ring; summarized at the end). */
  frame(ms: number) {
    this.frames.push(ms);
    if (this.frames.length > 3600) this.frames.shift();
  }

  onEvent(e: SimEvent, sim: SimView) {
    const c = this.challenge;
    if (!c) return;
    if (e.type === 'serve') {
      if (this.pitch) this.closePitch(sim, 'drain');
      this.openPitch(sim);
      return;
    }
    const p = this.pitch;
    switch (e.type) {
      case 'swing':
        if (p) {
          if (this.swingOpen) p.swingsMissed++;
          p.swings++;
          this.swingOpen = true;
        }
        break;
      case 'bat':
        if (p) {
          p.batHits++;
          if (e.sweet) p.sweetSpots = (p.sweetSpots ?? 0) + 1;
          this.swingOpen = false;
        }
        break;
      case 'score':
        this.onScore(c, e, sim);
        break;
      case 'machine': {
        if (e.kind === 'wall') break;
        const m = this.mech(c, e.id, e.kind);
        m.hits = (m.hits ?? 0) + 1;
        break;
      }
      case 'ramp': {
        const r = this.ramp(c, e.id);
        if (e.phase === 'enter') r.entries++;
        else if (e.phase === 'complete') {
          r.completes++;
          const ride = this.rides.get(e.ball) ?? 0;
          r.bestRide = Math.max(r.bestRide, ride + e.points);
          this.rides.delete(e.ball);
        } else if (e.phase === 'rollback') {
          r.rollbacks++;
          this.rides.delete(e.ball);
        } else if (e.phase === 'land') r.landings++;
        if (e.phase === 'enter') this.rides.set(e.ball, 0);
        break;
      }
      case 'rampCheckpoint': {
        const r = this.ramp(c, e.id);
        while (r.checkpointHits.length < e.count) {
          r.checkpointHits.push(0);
          r.checkpointPoints.push(0);
        }
        r.checkpointHits[e.index]++;
        r.checkpointPoints[e.index] += e.points;
        this.rides.set(e.ball, (this.rides.get(e.ball) ?? 0) + e.points);
        break;
      }
      case 'rampGate': {
        const r = this.ramp(c, e.id);
        r.gateHits++;
        r.gatePoints += e.points;
        this.rides.set(e.ball, (this.rides.get(e.ball) ?? 0) + e.points);
        break;
      }
      case 'scoop':
        if (e.phase === 'catch') c.scoops.catches++;
        else c.scoops.ejects++;
        break;
      case 'multiball':
        c.multiballs.activations++;
        c.multiballs.ballsLaunched++;
        if (p) {
          p.multiballs++;
          p.ballsLaunched++;
          p.maxBalls = Math.max(p.maxBalls, e.balls);
        }
        break;
      case 'mult': {
        const k = `${e.source}:${e.id}`;
        const g = (c.multGains[k] ??= { source: e.source, id: e.id, procs: 0, tenths: 0 });
        g.procs++;
        g.tenths += e.gain;
        const m = this.mech(c, e.id, e.source === 'gate' ? 'multgate' : e.source);
        m.multProcs++;
        m.multTenths += e.gain;
        c.multPeak = Math.max(c.multPeak, e.total);
        if (p) p.multPeak = Math.max(p.multPeak, e.total);
        break;
      }
      case 'deckRally': {
        const dr = c.deckRally;
        if (!dr) break;
        if (e.phase === 'start') dr.starts++;
        else if (e.reason === 'returned') dr.returned++;
        else if (e.reason === 'drain') dr.drained++;
        else dr.removed++;
        this.log('deckRally', { phase: e.phase, ball: e.ball, ...(e.reason ? { reason: e.reason, hits: e.hits, gained: e.gained } : {}) });
        break;
      }
      case 'drain':
        if (!p) break;
        if (e.foul) {
          // forgiven untouched pitch: it ends here like a drain, without a strike
          p.foul = true;
          p.drainSide = e.side;
          this.closePitch(sim, 'drain');
          this.save();
          break;
        }
        if (!e.strike) {
          p.extraBallDrains++;
          break;
        }
        p.drainSide = e.side;
        this.closePitch(sim, 'drain');
        this.save(); // strike = meaningful transition
        break;
      case 'clear':
        if (p) this.closePitch(sim, 'clear');
        break;
    }
  }

  private onScore(c: ChallengeRecord, e: Extract<SimEvent, { type: 'score' }>, sim: SimView) {
    const key = `${e.kind}:${e.id}${e.part ? ':' + e.part : ''}`;
    const s = (c.sources[key] ??= { kind: e.kind, id: e.id, awards: 0, awarded: 0, base: 0, modified: 0, best: 0 });
    s.awards++;
    s.awarded += e.awarded;
    s.base += e.base;
    s.modified += e.modified;
    s.best = Math.max(s.best, e.awarded);
    c.attributed += e.awarded;
    // Mechanism roll-up: ramp parts (checkpoints, gate) belong to their ramp instance.
    const isRamp = e.kind === 'ramp' || e.kind === 'rampGate' || e.kind === 'rampCheckpoint';
    const mid = isRamp ? e.id.replace(RAMP_PART, '') : e.id;
    const m = this.mech(c, mid, isRamp ? 'ramp' : e.kind);
    m.awards++;
    m.awarded += e.awarded;
    m.base += e.base;
    m.modified += e.modified;
    m.best = Math.max(m.best, e.awarded);
    const dr = c.deckRally;
    if (dr) {
      if (e.kind === 'ramp' && e.id === 'hr-ramp') {
        dr.hrCompletion += e.awarded;
        dr.hrCompletions++;
      }
      if (e.deckRally !== undefined || (DECK_PART.test(e.id) && (e.kind === 'bumper' || e.kind === 'sling'))) {
        dr.deckAwarded += e.awarded;
        dr.deckHits++;
      }
      if (e.rallyGain) {
        dr.rallyGain += e.rallyGain;
        dr.rallyHits++;
      }
    }
    const p = this.pitch;
    if (p) p.bestEvent = Math.max(p.bestEvent, e.awarded);
    const h: Highlight = { awarded: e.awarded, kind: e.kind, id: e.id, part: e.part, multTenths: e.multTenths, challenge: c.n, pitch: p?.n ?? sim.rules.pitchNumber, t: Math.round(this.now() - this.rec!.startedAt) };
    pushTop(c.bestEvents, h, 5);
    pushTop(this.rec!.highlights, h, LIMITS.highlights);
  }

  private openPitch(sim: SimView) {
    const c = this.challenge!;
    const m = sim.rules.multTenths;
    this.pitch = {
      n: sim.rules.pitchNumber,
      outcome: 'open',
      startScore: sim.rules.score,
      points: 0,
      simSeconds: 0,
      realSeconds: 0,
      startedAt: this.now(),
      swings: 0,
      batHits: 0,
      swingsMissed: 0,
      extraBallDrains: 0,
      multiballs: 0,
      ballsLaunched: 0,
      maxBalls: 1,
      multStart: m,
      multEnd: m,
      multPeak: m,
      bestEvent: 0,
    };
    (this.pitch as PitchRecord & { simStart: number }).simStart = sim.time;
    if (c.pitches.length < LIMITS.pitchesPerChallenge) c.pitches.push(this.pitch);
    this.swingOpen = false;
  }

  private closePitch(sim: SimView, outcome: 'drain' | 'clear') {
    const p = this.pitch as (PitchRecord & { simStart?: number }) | null;
    if (!p) return;
    if (this.swingOpen) p.swingsMissed++;
    this.swingOpen = false;
    p.outcome = outcome;
    p.points = sim.rules.score - p.startScore;
    p.simSeconds = +(sim.time - (p.simStart ?? sim.time)).toFixed(2);
    p.realSeconds = +((this.now() - p.startedAt) / 1000).toFixed(2);
    p.multEnd = sim.rules.multTenths;
    p.multPeak = Math.max(p.multPeak, p.multEnd);
    delete p.simStart;
    this.pitch = null;
  }

  private mech(c: ChallengeRecord, id: string, kind: string) {
    return (c.mechanisms[id] ??= { id, kind, awards: 0, awarded: 0, base: 0, modified: 0, best: 0, multTenths: 0, multProcs: 0 });
  }

  private ramp(c: ChallengeRecord, id: string) {
    return (c.ramps[id] ??= { id, entries: 0, completes: 0, rollbacks: 0, checkpointHits: [], checkpointPoints: [], gateHits: 0, gatePoints: 0, bestRide: 0, landings: 0 });
  }

  // ───────── ledger / persistence ─────────

  private log(type: string, data: Record<string, unknown>) {
    const r = this.rec;
    if (!r) return;
    const c = r.challenges[r.challenges.length - 1];
    if (r.ledger.length >= LIMITS.ledger) {
      r.ledgerDropped++;
      return;
    }
    r.ledger.push({ seq: ++this.seq, t: Math.round(this.now() - r.startedAt), challenge: c?.n ?? 0, type, ...data });
  }

  private closeFrames() {
    const r = this.rec;
    if (!r || !this.frames.length) return;
    const s = [...this.frames].sort((a, b) => a - b);
    r.frame = { samples: s.length, avgMs: +(s.reduce((a, b) => a + b, 0) / s.length).toFixed(2), p95Ms: +s[Math.floor(s.length * 0.95)].toFixed(2), maxMs: +s[s.length - 1].toFixed(1) };
  }

  /** Persist the in-progress run (with any open pitch marked open). Failure is silent: memory still works. */
  save() {
    const r = this.rec;
    if (!r) return false;
    r.savedAt = this.now();
    if (r.outcome !== 'in-progress') return true;
    return this.safeSet(STORE_KEYS.current, JSON.stringify(r));
  }

  /** Snapshot for a report: a deep copy with frame stats; never mutates the live record. */
  snapshot(): RunRecord | null {
    if (!this.rec) return null;
    this.closeFrames();
    return structuredClone(this.rec);
  }

  private safeGet(k: string) {
    try {
      return this.store?.get(k) ?? null;
    } catch {
      return null;
    }
  }
  private safeSet(k: string, v: string, quiet = false) {
    try {
      this.store?.set(k, v);
      return !!this.store;
    } catch {
      if (!quiet && this.rec && !this.rec.notes.includes(STORAGE_NOTE)) this.rec.notes.push(STORAGE_NOTE);
      return false;
    }
  }
  private safeRemove(k: string) {
    try {
      this.store?.remove(k);
    } catch {
      /* ignore */
    }
  }
}

const STORAGE_NOTE = 'Browser storage was unavailable or full; this report comes from memory only and would not survive a reload.';

function pushTop(list: Highlight[], h: Highlight, n: number) {
  if (list.length >= n && h.awarded <= list[list.length - 1].awarded) return;
  list.push(h);
  list.sort((a, b) => b.awarded - a.awarded);
  if (list.length > n) list.length = n;
}

export function makeRunId(t: number) {
  const rand = Math.floor(Math.random() * 36 ** 4).toString(36).padStart(4, '0');
  return `${t.toString(36)}-${rand}`;
}

