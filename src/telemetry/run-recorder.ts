/**
 * Developer run analytics (build test only). Records one roguelite run: challenges, strikes/pitches,
 * credited points by source, mechanism instances, ramps, multiplier sources, and the build/economy ledger.
 *
 * - Observation only: it reads sim events (incl. the `score` event emitted by the single award boundary)
 *   and Run state; it never changes gameplay.
 * - Local only: persisted to browser storage at meaningful transitions (challenge start/end, strike,
 *   draft/shop actions), never per frame, never sent anywhere.
 * - Honest: counters that can't be observed are absent, not zero; an interrupted pitch is never shown
 *   as finished; attributed points are reconciled against the scoreboard.
 */
import type { SimEvent } from '../physics/sim.ts';
import type { Modifier } from '../machines/mechanisms.ts';

/** v2: bundles (item → parts), sales, dormancy, offer weighting origin, 15-challenge victory. */
export const SCHEMA = 'baseball-pinball/dev-run@2';
/** Older records still load in the report. */
export const SCHEMAS_READABLE = ['baseball-pinball/dev-run@1', SCHEMA];
export const STORE_KEYS = { current: 'bp.devRun.current', archive: 'bp.devRun.archive' } as const;
/** Bounds: memory/storage never grow without limit. */
export const LIMITS = { ledger: 4000, highlights: 25, pitchesPerChallenge: 12, archivedRuns: 3 };

export type BuildInfo = { version: string; commit: string; builtAt: string };

/** Minimal storage (localStorage in the browser, a Map in tests). Every call may fail; callers cope. */
export interface Store {
  get(key: string): string | null;
  set(key: string, value: string): void;
  remove(key: string): void;
}
export class MemoryStore implements Store {
  m = new Map<string, string>();
  get(k: string) {
    return this.m.get(k) ?? null;
  }
  set(k: string, v: string) {
    this.m.set(k, v);
  }
  remove(k: string) {
    this.m.delete(k);
  }
}

